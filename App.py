def render_generic_tab(report_title):
    df = load_data(report_title)
    if df.empty:
        st.warning(f"No master data file found at: Web_Output/{report_title}_Master.csv")
    else:
        if "Supervisor Name" in df.columns:
            df = df[~df["Supervisor Name"].astype(str).str.lower().str.strip().eq("jackie")]
        st.subheader(f"{report_title} Overview")
        st.dataframe(df, width="stretch")

