# Target Web_Output Directory (Generated by Merger.py for Streamlit)
BASE_DIR = Path(__file__).parent.resolve()
OUTPUT_DIR = BASE_DIR / "Web_Output"

@st.cache_data(ttl=60)
def load_data(report_name):
    file_path = OUTPUT_DIR / f"{report_name}_Master.csv"
    if file_path.exists():
        try:
            df = pd.read_csv(file_path, low_memory=False)
            if "Date" in df.columns:
                df["Date"] = pd.to_datetime(df["Date"], errors='coerce')
            return df
        except Exception as e:
            st.error(f"Error reading {file_path.name}: {e}")
            return pd.DataFrame()
    return pd.DataFrame()

# Helper Function to Clean Data, Tag Projects, and Compute OSA Flags
def prepare_availability_data(df):
    df = df.copy()
    
    # 1. Exclude Jackie
    if "Supervisor Name" in df.columns:
        df = df[~df["Supervisor Name"].astype(str).str.lower().str.strip().eq("jackie")]
        
    # 2. Tag IB Project vs Core
    brand_col = "Brand Name" if "Brand Name" in df.columns else ("Brand" if "Brand" in df.columns else None)
    if brand_col:
        is_ib = df[brand_col].astype(str).str.lower().str.strip().str.endswith("ib")
        df["Project"] = is_ib.map({True: "IB Project", False: "Core"})
    else:
        df["Project"] = "Core"

    # 3. Clean Gap Reason Column
    gap_col = "Gap Reason" if "Gap Reason" in df.columns else ("GapReason" if "GapReason" in df.columns else None)
    df["_clean_reason"] = df[gap_col].astype(str).str.lower().str.strip() if gap_col else ""

    # 4. Compute Base OSA Flag (1 if available/filled, 0 if gap/empty)
    sku_col = None
    possible_cols = ["Number of SKUs", "Number Of SKUs", "SKU Count", "Quantity", "Available"]
    for col in possible_cols:
        if col in df.columns:
            sku_col = col
            break
            
    if sku_col:
        numeric_series = pd.to_numeric(df[sku_col], errors='coerce').fillna(0)
        df["OSA_Flag"] = (numeric_series > 0).astype(int)
    else:
        if gap_col:
            df["OSA_Flag"] = df[gap_col].isna().astype(int) | df[gap_col].astype(str).str.strip().eq("").astype(int)
        else:
            df["OSA_Flag"] = 1
            
    return df

